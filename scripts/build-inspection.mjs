import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import * as k from "../.agents/skills/anatomy/kit/iso-kit.mjs";

// Anatomy geometry is generated once; no geometry engine ships to the browser.
const projection = { origin: [265, 383], scale: 1.4, azimuth: 45, elevation: 30 };
const solids = [];
const slab = (id, plan, z, height, tone = "metal") =>
	solids.push({ id, tone, depth: k.depthOf([plan.x + plan.w / 2, plan.y + plan.d / 2, z + height / 2], projection), ...k.slabOf(plan, z, height, projection, 8, 0.7) });
const round = (id, x, y, radius, z, height, tone = "metal") =>
	solids.push({ id, tone, depth: k.depthOf([x, y, z + height / 2], projection), ...k.cylinder(x, y, radius, z, height, projection, 64, 0.5) });

// Parts: mat, base, two bearing shoulders, eight cooling ribs, housing,
// machined lip, four mounted fastener stacks, and four rubber support feet.
for (const [i, [x, y]] of k.corners({ x: -92, y: -72, w: 184, d: 144 }, 18).entries()) {
	round(`foot-${i}`, x, y, 10, -9, 9, "dark");
}
slab("base", { x: -92, y: -72, w: 184, d: 144, r: 13 }, 0, 13);
for (const y of [-38, 22]) {
	slab(`shoulder-${y}`, { x: -52, y, w: 104, d: 16, r: 3 }, 13, 20);
}
for (let i = 0; i < 8; i++) {
	slab(`rib-${i}`, { x: -52, y: -36 + i * 9, w: 104, d: 3, r: 1 }, 33, 12);
}
round("housing", 0, 0, 48, 45, 16);
round("machined-seat", 0, 0, 44, 61, 3);
round("machined-lip", 0, 0, 39, 64, 5);
for (const [i, [x, y]] of k.corners({ x: -92, y: -72, w: 184, d: 144 }, 22).entries()) {
	round(`washer-${i}`, x, y, 10, 13, 2, "dark");
	round(`washer-face-${i}`, x, y, 8, 15, 1);
	round(`bolt-${i}`, x, y, 5, 16, 7, "dark");
	round(`bolt-face-${i}`, x, y, 4, 23, 1);
	round(`bolt-socket-${i}`, x, y, 2, 24, 0.2, "dark");
}
for (const x of [-85, 85]) round(`alignment-pin-${x}`, x, 0, 3, 13, 7, "dark");
const ordered = solids.sort((a, b) => a.depth - b.depth);
const aperture = k.ring(0, 0, 26, 69, projection, 80);
const bore = k.ring(0, 0, 26, 53, projection, 80);
const crack = k.onTop([[25, -18], [29, -15], [27, -11], [32, -8], [30, -4]], 69.5, projection);
const mark = k.onTop([[16, -25], [39, -25], [39, 4], [16, 4]], 70, projection, true);
assert.equal(solids.length, 40);
assert.ok(solids.every((solid) => solid.fill && solid.top && solid.outline));
assert.ok(!JSON.stringify(solids).includes("NaN"));
const data = { solids: ordered, aperture, bore, crack, mark };
writeFileSync(new URL("../src/components/inspection-part.ts", import.meta.url), `// Generated by node scripts/build-inspection.mjs using the Anatomy kit.\nexport const inspectionPart = ${JSON.stringify(data)};\n`);
console.log(`Inspection geometry: ${solids.length} supported parts; checks passed.`);
